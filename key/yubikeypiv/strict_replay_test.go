// C. Unchanged behaviour. Every input that the driver accepted before this change is still accepted with the same reported values, except the
// inputs that the new rules refuse. The baseline is written here from what the driver before the change did (the library's answer, the firmware
// floor, the comparisons of the plan, the kind of key), computed from the recorded answers of the corpus and not from the new code.

var oidForm = asn1.ObjectIdentifier{1, 3, 6, 1, 4, 1, 41482, 3, 9}

// What the old reading kept of the recorded policy numbers (piv-go's: 1 never, 2 once, 3 always, 4 and 5 biometric).
func qpPINOf(n int) card.PINPolicy {
	switch n {
	case 1:
		return card.PINNever
	case 2:
		return card.PINOnce
	}
	return 0
}

func qpTouchOf(n int) card.TouchPolicy {
	if n >= 1 && n <= 3 {
		return card.TouchPolicy(n)
	}
	return 0
}

func qpPINName(p card.PINPolicy) string {
	switch p {
	case card.PINNever:
		return "never"
	case card.PINOnce:
		return "once"
	}
	return "always"
}

func qpTouchName(p card.TouchPolicy) string {
	return map[card.TouchPolicy]string{card.TouchNever: "never", card.TouchAlways: "always", card.TouchCached: "cached"}[p]
}

// The inputs of my earlier tests of the adapter (the table of good chains), through the driver's peer path: which are still accepted with the
// same values, and which are refused now and why.
func TestQPTheEarlierGoodChainsAreStillAcceptedExceptTheOnesTheNewRulesRefuse(t *testing.T) {
	const serial = 1234567
	w := newQPWorld(t, serial, false, false)
	fw := func(a, b, c byte) pkix.Extension { return pkix.Extension{Id: oidFW, Value: []byte{a, b, c}} }
	ser := func(n int64) pkix.Extension {
		b, err := asn1.Marshal(n)
		if err != nil {
			t.Fatal(err)
		}
		return pkix.Extension{Id: oidSer, Value: b}
	}
	pol := func(p, tc byte) pkix.Extension { return pkix.Extension{Id: oidPol, Value: []byte{p, tc}} }
	form := func(b byte) pkix.Extension { return pkix.Extension{Id: oidForm, Value: []byte{b}} }
	all := func(f [3]byte, s int64, p, tc, ff byte) []pkix.Extension {
		return []pkix.Extension{fw(f[0], f[1], f[2]), ser(s), pol(p, tc), form(ff)}
	}
	tests := []struct {
		name     string
		cn       string
		ext      []pkix.Extension
		none     bool
		oldOK    bool // accepted by the peer path before this change
		want     string
		slot     string
		pin, tch string
		serial   uint32
	}{
		{name: "slot 9a, firmware 5.8.0, PIN once, touch never", cn: "9a", ext: all([3]byte{5, 8, 0}, 1234567, 2, 1, 4), oldOK: true, slot: "9a", pin: "once", tch: "never", serial: 1234567},
		{name: "slot 9c, PIN never, touch always", cn: "9c", ext: all([3]byte{5, 7, 4}, 1, 1, 2, 4), oldOK: true, slot: "9c", pin: "never", tch: "always", serial: 1},
		{name: "slot 9d, PIN always (read as none), touch cached", cn: "9d", ext: all([3]byte{5, 7, 0}, 7, 3, 3, 4), oldOK: true, slot: "9d", pin: "always", tch: "cached", serial: 7},
		{name: "slot 9e, a biometric PIN policy", cn: "9e", ext: all([3]byte{5, 8, 0}, 7, 4, 1, 4), oldOK: true, slot: "9e", pin: "always", tch: "never", serial: 7},
		{name: "slot 82, the other biometric PIN policy", cn: "82", ext: all([3]byte{5, 8, 0}, 7, 5, 1, 4), oldOK: true, slot: "82", pin: "always", tch: "never", serial: 7},
		{name: "slot 95, the largest serial and version", cn: "95", ext: all([3]byte{255, 254, 253}, 1<<32-1, 1, 1, 0xff), oldOK: true, slot: "95", pin: "never", tch: "never", serial: 1<<32 - 1},
		{name: "a serial of 2^32+5 is cut to 5", cn: "9a", ext: all([3]byte{5, 8, 0}, 1<<32+5, 2, 1, 4), oldOK: true, slot: "9a", pin: "once", tch: "never", serial: 5},
		{name: "serial 0", cn: "9a", ext: all([3]byte{5, 8, 0}, 0, 2, 1, 4), oldOK: true, slot: "9a", pin: "once", tch: "never", serial: 0},
		{name: "the form factor is not kept", cn: "9a", ext: all([3]byte{5, 8, 0}, 9, 2, 1, 0x85), oldOK: true, slot: "9a", pin: "once", tch: "never", serial: 9},
		{name: "a name that gives no slot: slot 0", cn: "f9", ext: all([3]byte{5, 8, 0}, 9, 2, 1, 4), oldOK: true, want: "origin: the answer is not of a key generated by a card"},
		{name: "no policy extension", cn: "9a", ext: []pkix.Extension{fw(5, 8, 0), ser(9)}, oldOK: true, want: "policy" + qpNotSaid},
		{name: "no firmware extension (below the floor before)", cn: "9a", ext: []pkix.Extension{ser(9), pol(2, 1)}, oldOK: false, want: "firmware" + qpNotSaid},
		{name: "no serial extension", cn: "9a", ext: []pkix.Extension{fw(5, 8, 0), pol(2, 1)}, oldOK: true, want: "serial" + qpNotSaid},
		{name: "no extension at all (below the floor before)", cn: "9c", none: true, oldOK: false, want: "firmware" + qpNotSaid},
	}
	newlyRefused, stillRefused := 0, 0
	for _, tt := range tests {
		slot, key := w.slot(t, qpSlot{cn: "YubiKey PIV Attestation " + tt.cn, ext: tt.ext, none: tt.none})
		o := qpPeer(t, w, w.f9, slot)
		if tt.want == "" {
			if !o.accepted() {
				t.Errorf("%s: refused now: %v", tt.name, o.err)
				continue
			}
			res, err := w.peerAnswer(t, w.f9, slot)
			if err != nil || res.slot != tt.slot || res.pin != tt.pin || res.touch != tt.tch || res.serial != tt.serial || !bytes.Equal(o.spki, qpSPKI(t, key)) {
				t.Errorf("%s: answered %+v, %v; want slot %s, PIN %s, touch %s, serial %d", tt.name, res, err, tt.slot, tt.pin, tt.tch, tt.serial)
			}
			continue
		}
		qpWantPeerRefusal(t, tt.name, o)
		if o.word != tt.want {
			t.Errorf("%s: the journal says %q, want %q", tt.name, o.word, tt.want)
		}
		if tt.oldOK {
			newlyRefused++
		} else {
			stillRefused++
		}
	}
	// the 14 inputs: 10 are still accepted, 3 are refused that were accepted (no slot, no policy, no serial), 2 were refused before (below the
	// floor, for lack of a firmware) and are refused now for what they lack
	if newlyRefused != 3 || stillRefused != 2 {
		t.Errorf("%d newly refused and %d refused before, want 3 and 2", newlyRefused, stillRefused)
	}
}

type qpAnswer struct {
	slot, pin, touch string
	serial           uint32
}

// peerAnswer is the answer of the peer path (the values it reports) for a slot certificate and its signer.
func (w *qpWorld) peerAnswer(t *testing.T, signer, slot *x509.Certificate) (qpAnswer, error) {
	t.Helper()
	q := &quirkCard{Card: cardtest.New(), verify: w.verify}
	s, _, err := startQuirk(t, q, factoryDefaults)
	if err != nil {
		return qpAnswer{}, err
	}
	res, err := s.VerifyAttestation(t.Context(), connect.NewRequest(&keyv1alpha1.VerifyAttestationRequest{Attestation: slot.Raw, AttestationSigner: signer.Raw}))
	if err != nil {
		return qpAnswer{}, err
	}
	return qpAnswer{res.Msg.GetSlot(), res.Msg.GetPinPolicy(), res.Msg.GetTouchPolicy(), res.Msg.GetSerial()}, nil
}

// The corpus of 224 cases through the driver's two paths. A case that the driver accepted before is still accepted with the same values, unless
// a new rule refuses it; the cases that are refused now and were not are counted by their reason, and nothing that was refused is accepted.
func TestQPTheCorpusThroughTheDriversPathsOnlyLosesWhatTheNewRulesRefuse(t *testing.T) {
	c, err := attesttest.Load()
	if err != nil {
		t.Fatal(err)
	}
	const cardSerial = 1234567
	worlds := map[string]*qpWorld{}
	for name, p := range c.PKIs {
		v, err := card.NewAttestationVerifier([]byte(p.RootPEM), []byte(p.BundlePEM), p.RootSHA256)
		if err != nil {
			t.Fatal(err)
		}
		worlds[name] = &qpWorld{verify: v, serial: cardSerial}
	}
	type tally struct {
		before, still int
		lost          map[string][]string // the reason, the cases
		gained        []string
	}
	adopt, peer := &tally{lost: map[string][]string{}}, &tally{lost: map[string][]string{}}
	judged := 0
	for _, cs := range c.Cases {
		if strings.Contains(cs.Name, "expired") || strings.Contains(cs.Name, "not-yet") {
			continue // the answer depends on the time: refused before and now
		}
		judged++
		slot, err := x509.ParseCertificate(cs.Slot)
		if err != nil {
			t.Fatal(err)
		}
		signer, err := x509.ParseCertificate(cs.Signer)
		if err != nil {
			t.Fatal(err)
		}
		w := worlds[cs.PKI]
		g := cs.Want
		floorOK := g.Firmware[0] > 5 || g.Firmware[0] == 5 && g.Firmware[1] >= 7
		ec, isEC := slot.PublicKey.(*ecdsa.PublicKey)
		oldPeer := g.OK && floorOK && isEC
		oldAdopt := g.OK && floorOK && g.Serial == cardSerial && g.Slot == 0x9a && qpPINOf(g.PIN) == card.PINOnce && qpTouchOf(g.Touch) == card.TouchNever &&
			isEC && ec.Curve == elliptic.P384()

		// the card layer: the reported values are the old reading's
		if g.OK {
			a, err := w.verify(signer, slot)
			if err != nil {
				t.Fatalf("%s: %v", cs.Name, err)
			}
			want := card.Attestation{Version: card.Version{Major: g.Firmware[0], Minor: g.Firmware[1], Patch: g.Firmware[2]}, Serial: g.Serial, Slot: card.Slot(g.Slot), PIN: qpPINOf(g.PIN), Touch: qpTouchOf(g.Touch)}
			if a.Reported() != want {
				t.Errorf("%s: reported %+v, want %+v", cs.Name, a.Reported(), want)
			}
		}

		// the adoption
		ao := qpAdopt(t, w, signer, slot)
		if oldAdopt {
			adopt.before++
			if ao.accepted() {
				adopt.still++
				if isEC && !bytes.Equal(ao.spki, qpSPKI(t, ec)) {
					t.Errorf("%s: adopted another key", cs.Name)
				}
			} else {
				adopt.lost[strings.SplitN(ao.word, ":", 2)[0]] = append(adopt.lost[strings.SplitN(ao.word, ":", 2)[0]], cs.Name)
			}
		} else if ao.accepted() {
			adopt.gained = append(adopt.gained, cs.Name)
		}

		// the peer path
		po := qpPeer(t, w, signer, slot)
		if oldPeer {
			peer.before++
			if po.accepted() {
				peer.still++
				if !bytes.Equal(po.spki, qpSPKI(t, ec)) {
					t.Errorf("%s: the peer path answered with another key", cs.Name)
				}
				res, err := w.peerAnswer(t, signer, slot)
				if want := (qpAnswer{card.Slot(g.Slot).String(), qpPINName(qpPINOf(g.PIN)), qpTouchName(qpTouchOf(g.Touch)), g.Serial}); err != nil || res != want {
					t.Errorf("%s: the peer path answered %+v, %v, want %+v", cs.Name, res, err, want)
				}
			} else {
				reason := strings.SplitN(po.word, ":", 2)[0]
				peer.lost[reason] = append(peer.lost[reason], cs.Name)
			}
		} else if po.accepted() {
			peer.gained = append(peer.gained, cs.Name)
		}
	}
	report := func(name string, tl *tally) string {
		var parts []string
		var reasons []string
		for r := range tl.lost {
			reasons = append(reasons, r)
		}
		sort.Strings(reasons)
		for _, r := range reasons {
			parts = append(parts, fmt.Sprintf("%s=%d", r, len(tl.lost[r])))
		}
		return fmt.Sprintf("%s: %d accepted before, %d still accepted, lost by reason {%s}, gained %d", name, tl.before, tl.still, strings.Join(parts, " "), len(tl.gained))
	}
	t.Log(report("adoption", adopt))
	t.Log(report("peer", peer))
	for _, r := range slices.Sorted(func(yield func(string) bool) {
		for k := range peer.lost {
			if !yield(k) {
				return
			}
		}
	}) {
		t.Logf("peer lost by %s: %v", r, peer.lost[r])
	}
	for _, r := range slices.Sorted(func(yield func(string) bool) {
		for k := range adopt.lost {
			if !yield(k) {
				return
			}
		}
	}) {
		t.Logf("adoption lost by %s: %v", r, adopt.lost[r])
	}
	if len(adopt.gained) != 0 || len(peer.gained) != 0 {
		t.Errorf("accepted now and refused before: adoption %v, peer %v", adopt.gained, peer.gained)
	}
	// What is lost, and why, from the recorded answers: a slot that no name gives (the answer's slot is 0) and a chain that is not exactly the slot
	// certificate, the card's certificate and a PIV intermediate lose their origin; a certificate that does not state the serial or the policy
	// loses for that. The firmware is the same as before for the cases that lack it (they were below the floor). The anchors given as the slot
	// certificate state nothing, so the old floor refused them already: none of the six is lost.
	byName := map[string]attesttest.Case{}
	for _, cs := range c.Cases {
		byName[cs.Name] = cs
	}
	for reason, names := range peer.lost {
		for _, n := range names {
			want := "origin"
			switch {
			case n == "absent-1.3.6.1.4.1.41482.3.7":
				want = "serial"
			case n == "absent-1.3.6.1.4.1.41482.3.8":
				want = "policy"
			case byName[n].Want.Slot != 0 && n != "f9-signed-by-root" && n != "signer-is-the-piv-intermediate":
				want = "unexpected"
			}
			if reason != want {
				t.Errorf("%s was lost by %s, want %s", n, reason, want)
			}
		}
	}
	for _, a := range []string{"piv-intermediate", "root"} {
		for _, sg := range []string{"unrelated", "f9", "itself"} {
			n := "slot-is-the-" + a + "-signer-" + sg
			for _, r := range peer.lost {
				if slices.Contains(r, n) {
					t.Errorf("%s was accepted by the peer path before this change", n)
				}
			}
			cs := byName[n]
			if floor := cs.Want.Firmware; floor[0] != 0 || floor[1] != 0 {
				t.Errorf("%s states a firmware: %v", n, floor)
			}
		}
	}
	lost := 0
	for _, names := range peer.lost {
		lost += len(names)
	}
	if peer.before != 129 || peer.still != 95 || lost != 34 || len(peer.lost["origin"]) != 32 || len(peer.lost["serial"]) != 1 || len(peer.lost["policy"]) != 1 || len(peer.lost) != 3 {
		t.Errorf("the peer path: %s", report("peer", peer))
	}
	if adopt.before != 1 || adopt.still != 1 || len(adopt.lost) != 0 {
		t.Errorf("the adoption: %s", report("adoption", adopt))
	}
	if judged < 200 {
		t.Errorf("only %d cases judged", judged)
	}
}
