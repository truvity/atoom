// A. The new refusals, each on both paths and each with a passing neighbour. A certificate that is not an attestation of a key a card made is
// refused for that, with the words and the class of every refusal of an attestation, which name no key, no serial and no certificate content.

const (
	qpOrigin  = "origin: the attestation does not show a key generated by a card"
	qpNotSaid = ": the attestation does not state it"
)

// qpPeerWord is the journal's reason on the peer path for the same refusals.
func qpPeerWord(adoptWord string) string {
	if adoptWord == qpOrigin {
		return "origin: the answer is not of a key generated by a card"
	}
	return adoptWord
}

type qpCase struct {
	w          *qpWorld
	slot       *x509.Certificate
	att        *x509.Certificate // the card's attestation certificate on adoption
	signers    []*x509.Certificate
	adoptWord  string // "" accepted
	peerWord   string // "" accepted
	checkLeaks bool
}

// run puts the case through both paths.
func (c qpCase) run(t *testing.T, serial uint32) {
	t.Helper()
	if c.att == nil {
		c.att = c.w.f9
	}
	if len(c.signers) == 0 {
		c.signers = []*x509.Certificate{c.att}
	}
	a := qpAdopt(t, c.w, c.att, c.slot)
	if c.adoptWord == "" {
		if !a.accepted() {
			t.Errorf("adoption: refused: %v", a.err)
		}
	} else {
		if a.accepted() {
			t.Fatalf("adoption: accepted, want %q", c.adoptWord)
		}
		if a.word != c.adoptWord {
			t.Errorf("adoption: the word is %q, want %q", a.word, c.adoptWord)
		}
		if c.checkLeaks {
			if l := qpLeaks(a.err.Error(), c.slot, serial, true); len(l) > 0 {
				t.Errorf("adoption: the words hold %v: %q", l, a.err)
			}
		}
	}
	for _, signer := range c.signers {
		p := qpPeer(t, c.w, signer, c.slot)
		if c.peerWord == "" {
			if !p.accepted() {
				t.Errorf("peer (signer %q): refused: %v", signer.Subject.CommonName, p.err)
			}
			continue
		}
		qpWantPeerRefusal(t, "peer (signer "+signer.Subject.CommonName+")", p)
		if p.word != qpPeerWord(c.peerWord) {
			t.Errorf("peer (signer %q): the journal says %q, want %q", signer.Subject.CommonName, p.word, qpPeerWord(c.peerWord))
		}
		if c.checkLeaks {
			if l := qpLeaks(p.err.Error(), c.slot, serial, true); len(l) > 0 {
				t.Errorf("peer: the words hold %v: %q", l, p.err)
			}
			// the journal says the common name of the anchor on purpose (the field anchor): nothing else of the certificate
			var journal string
			for _, l := range p.rec.got() {
				for _, at := range l.attrs {
					journal += " " + at.Value.String()
				}
			}
			if l := qpLeaks(journal, c.slot, serial, false); len(l) > 0 {
				t.Errorf("peer: the journal holds %v: %q", l, journal)
			}
		}
	}
}

// A certificate that is itself a trust anchor verifies as a chain of one, whoever the signer is. The root here names slot 9a and states the
// firmware, the serial and the policies that the plan asks, so that every comparison of the driver before this change passes. The PIV
// intermediate cannot name a slot (an admitted intermediate is named "Yubico PIV Attestation ..."): on adoption the old comparison of the slot
// would refuse it, and the origin is now the first refusal; on the peer path, which compares no slot, the old driver took it, stating
// firmware 5.8.0, and answered with its key.
func TestQPATrustAnchorGivenAsTheSlotCertificateIsRefusedOnBothPaths(t *testing.T) {
	const serial = 12345678
	good := newQPWorld(t, serial, false, false)
	rooted := newQPWorld(t, serial, true, false)
	pivd := newQPWorld(t, serial, false, true)

	goodSlot, _ := good.slot(t, qpSlot{})
	// the neighbour: a slot certificate signed by the card's attestation certificate, in a PKI whose root and intermediate state the same
	rootedSlot, _ := rooted.slot(t, qpSlot{})
	pivdSlot, _ := pivd.slot(t, qpSlot{})
	for name, c := range map[string]qpCase{
		"a good chain, with plain anchors":                        {w: good, slot: goodSlot},
		"a good chain, under a root that states what a slot does": {w: rooted, slot: rootedSlot},
		"a good chain, under an intermediate that states them":    {w: pivd, slot: pivdSlot},
		"the root as the slot certificate (signer: the card's)": {
			w: rooted, slot: rooted.root, signers: []*x509.Certificate{rooted.f9, rooted.piv, rooted.root},
			adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
		"the PIV intermediate as the slot certificate": {
			w: pivd, slot: pivd.piv, signers: []*x509.Certificate{pivd.f9, pivd.piv, pivd.root},
			adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
	} {
		t.Run(name, func(t *testing.T) { c.run(t, serial) })
	}
	// what the old driver took, shown by the reading it made (the card layer is unchanged): the chain passes and every comparison passes
	spec := card.KeySpec{Algorithm: card.EC384, PIN: card.PINOnce, Touch: card.TouchNever}
	a, err := rooted.verify(rooted.f9, rooted.root)
	if err != nil || !oldDriverAccepts(a, serial, 0x9a, spec) || a.Evidence.Generated || a.MissingFact() != "" {
		t.Fatalf("the root as the slot certificate is not what this test means: %+v, %v", a, err)
	}
	a, err = pivd.verify(pivd.f9, pivd.piv)
	if err != nil || a.Version.AtLeast(5, 7, 0) == false || a.Evidence.Generated || a.MissingFact() != "slot" {
		t.Fatalf("the PIV intermediate as the slot certificate is not what this test means: %+v, %v", a, err)
	}
	if oldDriverAccepts(a, serial, 0x9a, spec) {
		t.Error("the old comparison of the slot passes for an intermediate: it cannot name one")
	}
}

// A slot certificate signed directly by the PIV intermediate, or by the root, leaves the card's attestation certificate out of the chain: the
// chain verifies (as a chain of two), every comparison of the old driver passes, and only the new rule refuses it. A slot certificate under an
// attestation certificate that the root signed is a chain of three that ends in the root, not in a PIV intermediate: the same.
func TestQPASlotCertificateSignedByAnAnchorIsRefusedOnBothPaths(t *testing.T) {
	const serial = 12345678
	w := newQPWorld(t, serial, false, false)
	spec := card.KeySpec{Algorithm: card.EC384, PIN: card.PINOnce, Touch: card.TouchNever}
	good, _ := w.slot(t, qpSlot{})
	byPIV, _ := w.slot(t, qpSlot{by: "piv"})
	byRoot, _ := w.slot(t, qpSlot{by: "root"})
	underRootF9, _ := w.slot(t, qpSlot{by: "f9-of-root"})
	for name, in := range map[string][2]*x509.Certificate{
		"by the PIV intermediate": {w.f9, byPIV}, "by the root": {w.f9, byRoot}, "under an attestation certificate signed by the root": {w.f9OfRoot, underRootF9},
	} {
		a, err := w.verify(in[0], in[1])
		if err != nil || !oldDriverAccepts(a, serial, 0x9a, spec) || a.Evidence.Generated || a.MissingFact() != "" {
			t.Fatalf("%s is not what this test means: %+v, %v", name, a, err)
		}
	}
	for name, c := range map[string]qpCase{
		"a slot certificate signed by the attestation certificate": {w: w, slot: good},
		"signed directly by the PIV intermediate":                  {w: w, slot: byPIV, adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true},
		"signed directly by the root":                              {w: w, slot: byRoot, adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true},
		"under an attestation certificate that the root signed": {
			w: w, slot: underRootF9, att: w.f9OfRoot, signers: []*x509.Certificate{w.f9OfRoot}, adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
	} {
		t.Run(name, func(t *testing.T) { c.run(t, serial) })
	}
	// the signer given on the peer path does not matter for a slot certificate signed by an anchor: with the right one, an unrelated one, the root
	for _, signer := range []*x509.Certificate{w.f9, w.root, byPIV} {
		qpWantPeerRefusal(t, "signed by the PIV intermediate, signer "+signer.Subject.CommonName, qpPeer(t, w, signer, byPIV))
	}
}

// Each fact that the attestation does not state, in turn and all together. The firmware, the serial and the policy are refused for what they are
// (their value would be read as zero: the version 0.0.0, the serial 0, a PIN policy that no plan names); a slot that the name does not give
// leaves the library's Generated false, so it is refused for its origin, which is the first check. The words are the ones of the driver, the
// class is the refusal of every attestation, and the first fact in the order firmware, serial, slot, policy is the one named.
func TestQPAFactTheAttestationDoesNotStateIsRefusedOnBothPaths(t *testing.T) {
	const serial = 12345678
	w := newQPWorld(t, serial, false, false)
	fw, ser, pol := qpStates(t, serial)[0], qpStates(t, serial)[1], qpStates(t, serial)[2]
	good, _ := w.slot(t, qpSlot{})
	o := func(s qpSlot) *x509.Certificate { c, _ := w.slot(t, s); return c }
	for name, c := range map[string]qpCase{
		"nothing left out": {w: w, slot: good},
		"the firmware": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{ser, pol}}), adoptWord: "firmware" + qpNotSaid, peerWord: "firmware" + qpNotSaid, checkLeaks: true,
		},
		"the serial": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{fw, pol}}), adoptWord: "serial" + qpNotSaid, peerWord: "serial" + qpNotSaid, checkLeaks: true,
		},
		"the policy": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{fw, ser}}), adoptWord: "policy" + qpNotSaid, peerWord: "policy" + qpNotSaid, checkLeaks: true,
		},
		"the slot (the name gives none)": {w: w, slot: o(qpSlot{cn: "YubiKey PIV Attestation f9"}), adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true},
		"the slot (a name that is no slot's)": {
			w: w, slot: o(qpSlot{cn: "an attestation"}), adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
		"the serial and the policy: the serial is named": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{fw}}), adoptWord: "serial" + qpNotSaid, peerWord: "serial" + qpNotSaid, checkLeaks: true,
		},
		"the firmware and the policy: the firmware is named": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{ser}}), adoptWord: "firmware" + qpNotSaid, peerWord: "firmware" + qpNotSaid, checkLeaks: true,
		},
		"every extension": {w: w, slot: o(qpSlot{none: true}), adoptWord: "firmware" + qpNotSaid, peerWord: "firmware" + qpNotSaid, checkLeaks: true},
		"every extension and the slot": {
			w: w, slot: o(qpSlot{none: true, cn: "an attestation"}), adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
		"the firmware and the slot": {
			w: w, slot: o(qpSlot{ext: []pkix.Extension{ser, pol}, cn: "an attestation"}), adoptWord: qpOrigin, peerWord: qpOrigin, checkLeaks: true,
		},
	} {
		t.Run(name, func(t *testing.T) { c.run(t, serial) })
	}
}

// The journal line of a refusal is still written, on both paths, for a chain that does not verify and for the new refusals, at the level of a
// warning and with the attributes that the driver always wrote: on adoption the slot and the reason, on the peer path the reason, and, for the
// refusal that the caller sees, the line of every refusal (method, code, reason, field). A refusal for a missing fact on adoption comes back
// as the problem of the start; the driver writes no line of its own for it (nor for the comparisons of the serial and the policies, which
// never had one), so that nothing is asserted of the journal there.
func TestQPTheJournalLineOfARefusalIsStillWritten(t *testing.T) {
	const serial = 12345678
	w := newQPWorld(t, serial, true, false)
	other := newQPWorld(t, serial, false, false)
	rogue, _ := other.slot(t, qpSlot{})
	root := w.root
	noFW, _ := w.slot(t, qpSlot{ext: qpStates(t, serial)[1:]})

	for _, c := range []struct {
		name       string
		slot       *x509.Certificate
		reason     string // the beginning of the "error" of the line
		adoptLine  bool   // a line of its own on adoption
		peerLine   bool
		adoptAttrs []string
		peerAttrs  []string
	}{
		{"a chain that does not verify", rogue, "x509", true, true, []string{"slot", "error"}, []string{"error"}},
		{"a trust anchor as the slot certificate", root, "", true, true, []string{"slot", "error", "slot_named", "anchor"}, []string{"error", "slot_named", "anchor"}},
		{"a fact that is not stated", noFW, "", false, true, nil, []string{"error"}},
	} {
		t.Run(c.name, func(t *testing.T) {
			a := qpAdopt(t, w, w.f9, c.slot)
			if a.accepted() {
				t.Fatal("adoption accepted")
			}
			var lines []logLine
			for _, l := range a.rec.got() {
				if l.msg == "attestation refused" {
					lines = append(lines, l)
				}
			}
			switch {
			case c.adoptLine && len(lines) != 1:
				t.Fatalf("adoption wrote %d lines %q, want one: %v", len(lines), "attestation refused", a.rec.messages())
			}
			if c.adoptLine {
				l := lines[0]
				if l.level != slog.LevelWarn || strings.Join(l.keys(), ",") != strings.Join(c.adoptAttrs, ",") || l.attrs[0].Value.String() != "9a" {
					t.Errorf("adoption: the line is %v %v", l.level, l.keys())
				}
				if strings.HasPrefix(c.reason, "x509") && !strings.HasPrefix(l.attrs[1].Value.String(), "error verifying attestation certificate: ") {
					t.Errorf("adoption: the chain error is %q", l.attrs[1].Value.String())
				}
			}
			p := qpPeer(t, w, w.f9, c.slot)
			qpWantPeerRefusal(t, c.name, p)
			var refused, peer []logLine
			for _, l := range p.rec.got() {
				switch l.msg {
				case "refused":
					refused = append(refused, l)
				case "a peer's attestation refused":
					peer = append(peer, l)
				}
			}
			if len(peer) != 1 || peer[0].level != slog.LevelWarn || strings.Join(peer[0].keys(), ",") != strings.Join(c.peerAttrs, ",") {
				t.Fatalf("peer: the lines %v", peer)
			}
			if len(refused) != 1 || refused[0].level != slog.LevelWarn {
				t.Fatalf("peer: the refusal line %v", refused)
			}
			got := map[string]string{}
			for _, at := range refused[0].attrs {
				got[at.Key] = at.Value.String()
			}
			if got["method"] != "VerifyAttestation" || got["code"] != "failed_precondition" || got["reason"] != "attestation" || got["field"] != "attestation" {
				t.Errorf("peer: the refusal line says %v", got)
			}
		})
	}
}
